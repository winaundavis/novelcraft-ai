def build_priority_block() -> str:
    """生成 8 级优先级指令块（供生成 prompt 注入）。"""
    lines = ["写作优先级（从高到低，冲突时高优先级覆盖低优先级）："]
    for level, instruction in PRIORITY_INSTRUCTIONS:
        lines.append(f"- {level}：{instruction}")
    return "\n".join(lines)


def build_rubric_generation_instructions() -> str:
    """生成 D1-D10 生成侧文风/质量硬性指令块（评分量表检查点 → 写作要求）。"""
    lines = ["【文风与质量硬性指令（生成时即规避常见问题，不要留到修改阶段）】"]
    for dim in ("D1", "D2", "D3", "D4", "D5", "D6", "D7", "D8", "D9", "D10"):
        instruction = RUBRIC_TO_GENERATION_INSTRUCTIONS[dim]
        label = dim
        lines.append(f"- {label}：{instruction}")
    return "\n".join(lines)


def build_full_style_contract_block() -> str:
    """生成完整生成侧风格契约块：8 级优先级 + D1-D10 硬性指令。"""
    return "\n\n".join(
        [
            build_priority_block(),
            build_rubric_generation_instructions(),
        ]
    )


def build_priority_summary() -> str:
    """生成一行精简优先级摘要（供补写/扩写 prompt 注入，避免重复长指令）。"""
    return "、".join(level for level, _ in PRIORITY_INSTRUCTIONS)
